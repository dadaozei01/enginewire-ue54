#!/usr/bin/env python3
"""Build the native capability shard for this repository's own commands.

Upstream generates MCP/Generated/ from its TypeScript catalog (scripts/generate-canonical-registry.ts, not in this
repository), and those files say "do not edit". Commands added here keep their records in
MCP/Extensions/*.capabilities.json instead; this script turns them into MCP/Extensions/McpExtensionCapabilityShards.*
in the same chunked JSON form, adding legacyIds and sha256 hashes. The capability store loads them after the generated
shards. Run it after changing a .capabilities.json file:

    python3 scripts/gen-extension-capabilities.py
"""

import glob
import hashlib
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXT_DIR = os.path.join(ROOT, "plugins", "EngineWire", "Source", "EngineWire", "Private", "MCP", "Extensions")
CHUNK = 4000  # characters of JSON per TEXT() literal, well under MSVC's per-literal limit


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True)


def sha256(value):
    return hashlib.sha256(canonical(value).encode("ascii")).hexdigest()


def finish(record):
    action = record["id"].split(".", 1)[1]
    parent = record["routing"]["parentTool"]
    record.setdefault("aliases", [])
    record["legacyIds"] = [{"tool": parent, "action": action}]
    record.pop("hashes", None)
    record["hashes"] = {
        "algorithm": "sha256",
        "schema": sha256(record["schemas"]),
        "content": sha256({k: v for k, v in record.items() if k != "hashes"}),
    }
    return {"record": record}


def escape(text):
    return text.replace("\\", "\\\\").replace('"', '\\"')


def main():
    entries = []
    for path in sorted(glob.glob(os.path.join(EXT_DIR, "*.capabilities.json"))):
        with open(path, encoding="utf-8") as handle:
            entries += [finish(record) for record in json.load(handle)]
    ids = [entry["record"]["id"] for entry in entries]
    if len(ids) != len(set(ids)):
        sys.exit("duplicate capability id in MCP/Extensions")
    payload = json.dumps(entries, separators=(",", ":"), ensure_ascii=True)
    chunks = [payload[i:i + CHUNK] for i in range(0, len(payload), CHUNK)]
    # The catalog revision clients may pin covers the generated catalog and these records together.
    with open(os.path.join(os.path.dirname(EXT_DIR), "Generated", "McpGeneratedCapabilityShards.h"), encoding="ascii") as handle:
        generated = re.search(r'CatalogRevision\(\) \{ return TEXT\("([0-9a-f]+)"\); \}', handle.read()).group(1)
    revision = hashlib.sha256((generated + payload).encode("ascii")).hexdigest()[:16]

    header = """// GENERATED by scripts/gen-extension-capabilities.py from MCP/Extensions/*.capabilities.json -- do not edit.
#pragma once

#include "CoreMinimal.h"
#include "MCP/Generated/McpGeneratedCapabilityShards.h"

// This repository's own capability records, in the generated shards' form, loaded after them by the capability store.
namespace McpExtensionCapabilityShards
{
namespace Detail
{
\textern const TCHAR* const MCP_CAP_EXTENSION_CHUNKS[];
}

inline int32 Num() { return 1; }

inline const McpGeneratedCapabilityShards::FMcpCapabilityShard& At(int32 Index)
{
\tstatic const McpGeneratedCapabilityShards::FMcpCapabilityShard Table[] = {
\t\t{ TEXT("extensions"), Detail::MCP_CAP_EXTENSION_CHUNKS, %d, %d },
\t};
\tcheck(Index >= 0 && Index < Num());
\treturn Table[Index];
}

inline int32 TotalRecordCount() { return %d; }

// The catalog revision of the generated catalog (%s) and these records together. Rerun the script when the
// generated shards change, so this follows them.
inline const TCHAR* CatalogRevision() { return TEXT("%s"); }
}
""" % (len(chunks), len(entries), len(entries), generated, revision)

    body = ["// GENERATED by scripts/gen-extension-capabilities.py from MCP/Extensions/*.capabilities.json -- do not edit.",
            '#include "MCP/Extensions/McpExtensionCapabilityShards.h"', "",
            "// %s" % ", ".join(ids), "namespace McpExtensionCapabilityShards", "{", "namespace Detail", "{",
            "const TCHAR* const MCP_CAP_EXTENSION_CHUNKS[] = {"]
    body += ['\tTEXT("%s"),' % escape(chunk) for chunk in chunks]
    body += ["};", "}", "}", ""]

    with open(os.path.join(EXT_DIR, "McpExtensionCapabilityShards.h"), "w", encoding="ascii", newline="\n") as handle:
        handle.write(header)
    with open(os.path.join(EXT_DIR, "McpExtensionCapabilityShards.cpp"), "w", encoding="ascii", newline="\n") as handle:
        handle.write("\n".join(body))
    print("%d records, %d chunks, revision %s" % (len(entries), len(chunks), revision))


if __name__ == "__main__":
    main()
